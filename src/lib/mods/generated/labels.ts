// How the UI names a generated block: its synthesized display name and the
// generating mod, whether the resolution was a guess, or which mods to load
// to resolve it.
//
// Worker-safe: no DOM access.

import { getGeneratedBlockProvider, resolveGeneratedBlock } from "./registry";
import type {
  GeneratedBlockNeedsMods,
  GeneratedBlockProperties,
} from "./types";

/** Tooltip of the "approximate" hint on a heuristically resolved block. */
export const APPROXIMATE_GENERATED_BLOCK_HINT =
  "Exact variant unknown; guessed from block order";

export type GeneratedBlockLabel =
  | {
      kind: "resolved";
      /** The generating mod, e.g. "Unlimited Chisel Works". */
      modName: string;
      displayName: string;
      /** True when the source variant was guessed (show the hint). */
      approximate: boolean;
    }
  | {
      kind: "needs-mods";
      modName: string;
      /** What to load, from `generatedNeedsModsMessage`. */
      message: string;
    };

function namespaceOf(id: string): string {
  const colon = id.indexOf(":");
  return colon < 0 ? "minecraft" : id.slice(0, colon);
}

function joinNames(names: readonly string[]): string {
  if (names.length <= 1) return names.join("");
  return `${names.slice(0, -1).join(", ")} and ${names[names.length - 1]}`;
}

/**
 * "Generated by Unlimited Chisel Works from natura:nether_planks — load
 * Chisel and Natura for 1.12.2 to resolve it". `modNameFor` names a
 * namespace's mod (defaults to the namespace).
 */
export function generatedNeedsModsMessage(
  resolution: Pick<GeneratedBlockNeedsMods, "namespaces" | "sourceBlocks">,
  modName: string,
  gameVersion: string,
  modNameFor: (namespace: string) => string = (namespace) => namespace,
): string {
  const from = resolution.sourceBlocks[0];
  const names = [...new Set(resolution.namespaces.map(modNameFor))];
  return (
    `Generated by ${modName}${from === undefined ? "" : ` from ${from}`}` +
    ` — load ${joinNames(names)} for ${gameVersion} to resolve it`
  );
}

/**
 * The label of block state `id[properties]` against the files loaded for
 * `gameVersion` (resolve after `loadGeneratedBlockFiles`), or null when no
 * provider recognises it.
 */
export function generatedBlockLabel(
  id: string,
  properties: GeneratedBlockProperties,
  gameVersion: string,
  modNameFor?: (namespace: string) => string,
): GeneratedBlockLabel | null {
  const provider = getGeneratedBlockProvider(namespaceOf(id));
  if (provider === null) return null;
  const resolution = resolveGeneratedBlock(id, properties, gameVersion);
  if (resolution.kind === "resolved") {
    return {
      kind: "resolved",
      modName: provider.modName,
      displayName: resolution.block.displayName,
      approximate: resolution.approximate,
    };
  }
  if (resolution.kind === "needs-mods") {
    return {
      kind: "needs-mods",
      modName: provider.modName,
      message: generatedNeedsModsMessage(
        resolution,
        provider.modName,
        gameVersion,
        modNameFor,
      ),
    };
  }
  return null;
}
