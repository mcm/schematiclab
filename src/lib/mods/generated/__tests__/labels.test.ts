// Material-list labels of generated blocks, with the UCW provider and the
// hand-made files of `ucw-test-files.ts`.

import "fake-indexeddb/auto";

import { IDBFactory } from "fake-indexeddb";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

import * as modRegistry from "../../registry";
import * as store from "../../store";
import {
  APPROXIMATE_GENERATED_BLOCK_HINT,
  generatedBlockLabel,
  generatedNeedsModsMessage,
} from "../labels";
import {
  __setGeneratedVanillaLoaderForTests,
  loadGeneratedBlockFiles,
} from "../registry";
import { ID, VANILLA, loadAll } from "./ucw-test-files";

beforeEach(async () => {
  await store.__resetModStoreForTests();
  modRegistry.__resetLoadedModsForTests();
  globalThis.indexedDB = new IDBFactory();
  __setGeneratedVanillaLoaderForTests(async () => VANILLA);
});

afterEach(() => {
  __setGeneratedVanillaLoaderForTests(null);
});

describe("generatedNeedsModsMessage", () => {
  it("names the from block and the mods to load", () => {
    expect(
      generatedNeedsModsMessage(
        {
          namespaces: ["chisel", "natura"],
          sourceBlocks: ["natura:nether_planks", "chisel:planks-oak"],
        },
        "Unlimited Chisel Works",
        "1.12.2",
        (ns) => ({ chisel: "Chisel", natura: "Natura" })[ns] ?? ns,
      ),
    ).toBe(
      "Generated by Unlimited Chisel Works from natura:nether_planks — load Chisel and Natura for 1.12.2 to resolve it",
    );
    expect(
      generatedNeedsModsMessage(
        { namespaces: ["a", "b", "c"], sourceBlocks: [] },
        "Gen",
        "1.12.2",
      ),
    ).toBe("Generated by Gen — load a, b and c for 1.12.2 to resolve it");
  });
});

describe("generatedBlockLabel", () => {
  it("is null outside provider namespaces and for unknown ids", async () => {
    await loadAll();
    await loadGeneratedBlockFiles("1.12.2");
    expect(generatedBlockLabel("minecraft:stone", {}, "1.12.2")).toBeNull();
    expect(
      generatedBlockLabel("unlimitedchiselworks:nothing_here_0", {}, "1.12.2"),
    ).toBeNull();
  });

  it("names a resolved block after its from and through blocks", async () => {
    await loadAll();
    await loadGeneratedBlockFiles("1.12.2");
    const label = generatedBlockLabel(ID, { variation: "0" }, "1.12.2");
    expect(label).toMatchObject({
      kind: "resolved",
      modName: "Unlimited Chisel Works",
      // The from state is a modded state found by the blockstate heuristic.
      approximate: true,
    });
    expect(label?.kind === "resolved" && label.displayName).toBe(
      "Nether Planks (Planks Oak)",
    );
    expect(APPROXIMATE_GENERATED_BLOCK_HINT).toBe(
      "Exact variant unknown; guessed from block order",
    );
  });

  it("says which mods to load when a source mod is missing", async () => {
    await loadAll(false);
    await loadGeneratedBlockFiles("1.12.2");
    expect(
      generatedBlockLabel(ID, {}, "1.12.2", (ns) =>
        ns === "natura" ? "Natura" : ns,
      ),
    ).toEqual({
      kind: "needs-mods",
      modName: "Unlimited Chisel Works",
      message:
        "Generated by Unlimited Chisel Works from natura:nether_planks — load Natura for 1.12.2 to resolve it",
    });
  });
});
