/**
 * The 1.13+ id of a 1.12 vanilla texture id (`minecraft:blocks/…`); any
 * other id unchanged.
 */
export function modernVanillaTextureId(id: string): string {
  const prefix = id.startsWith("minecraft:blocks/")
    ? "minecraft:blocks/"
    : id.startsWith("blocks/")
      ? "blocks/"
      : null;
  if (prefix === null) return id;
  const name = id.slice(prefix.length);
  return `minecraft:block/${Object.hasOwn(RENAMED, name) ? RENAMED[name] : name}`;
}

